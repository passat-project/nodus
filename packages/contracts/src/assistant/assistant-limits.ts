/**
 * Технические предохранители движка ассистента (ADR-0043 п. 12): квот
 * запросов НЕТ (решение владельца), защита — только от зацикливания и
 * разбухания контекста. Значения — общие для сервера, настроек и клиента:
 * UI показывает их как «только чтение», сервер применяет их же.
 */
export const ASSISTANT_LIMITS = {
  /** Максимум шагов агентного цикла (запрос модели + пачка инструментов). */
  maxSteps: 12,
  /** Потолок одного прогона: провайдер и инструменты получают AbortSignal. */
  maxRunSeconds: 120,
  /** Лимит символов результата одного инструмента (дальше — обрезка с пометкой). */
  maxToolResultChars: 16_000,
  /** Лимит параллельных вызовов инструментов в одном шаге. */
  maxParallelToolCalls: 3,
  /** Сколько последних сообщений истории уходит в промпт. */
  maxHistoryMessages: 30,
  /** Сколько строк отдаёт компактная проекция списка инструмента. */
  maxListRows: 20,
  /** Лимит сессий в списке (последние). */
  maxSessions: 50,
  /** Потолок длины текста сообщения сотрудника. */
  maxPromptChars: 4_000,
} as const;

/** Идентификатор инструмента: `module.action` (внешние — `ext.<server>.<tool>`). */
export const ASSISTANT_TOOL_ID_PATTERN = /^(?:ext\.[a-z0-9_]+|[a-z][a-z0-9_]*)\.([a-z][a-z0-9_]*)$/;
