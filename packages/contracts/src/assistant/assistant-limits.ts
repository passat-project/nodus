/**
 * Технические предохранители движка ассистента (ADR-0043 п. 12): квот
 * запросов НЕТ (решение владельца), защита — только от зацикливания и
 * разбухания контекста. Значения — общие для сервера, настроек и клиента:
 * UI показывает их как «только чтение», сервер применяет их же.
 */
export const ASSISTANT_LIMITS = {
  /** Максимум шагов агентного цикла (запрос модели + пачка инструментов). */
  maxSteps: 12,
  /** Потолок одного прогона: провайдер и инструменты получают AbortSignal. */
  maxRunSeconds: 120,
  /** Лимит символов результата одного инструмента (дальше — обрезка с пометкой). */
  maxToolResultChars: 16_000,
  /** Лимит параллельных вызовов инструментов в одном шаге. */
  maxParallelToolCalls: 3,
  /** Сколько последних сообщений истории уходит в промпт дословно. */
  maxHistoryMessages: 30,
  /**
   * Контекстное окно модели по умолчанию (токены). Переопределяется env
   * `ASSISTANT_CONTEXT_WINDOW_TOKENS`; окно конкретной модели провайдер не
   * сообщает, поэтому значение консервативное.
   */
  contextWindowTokens: 128_000,
  /**
   * Доля окна, после которой старые ответы ассистента сжимаются в сегменты
   * (решение владельца 18.11.2026: 50%, а не 80% — не работаем на большом
   * контексте).
   */
  contextCompactRatio: 0.5,
  /** Сколько сообщений покрывает один сегмент сжатия (порция, не вся история). */
  contextSegmentMessages: 40,
  /** Бюджет символов исходных сообщений одного сегмента. */
  contextSegmentInputChars: 60_000,
  /** Потолок текста сегмента: сводка не должна стать новым шумом. */
  contextSegmentMaxChars: 6_000,
  /** Сколько последних сегментов попадает в промпт (остальные — только в ленте). */
  contextMaxSegments: 8,
  /** Бюджет старых результатов инструментов в прогоне до очистки (символы). */
  toolResultBudgetChars: 48_000,
  /** Сколько последних результатов инструментов не очищаются. */
  toolResultKeep: 6,
  /** Сколько строк отдаёт компактная проекция списка инструмента. */
  maxListRows: 20,
  /** Лимит сессий в списке (последние). */
  maxSessions: 50,
  /** Потолок длины текста сообщения сотрудника. */
  maxPromptChars: 4_000,
  /** Сколько карточек действий модель может предложить за один прогон:
   *  защита от «пачки нажатий» вместо объяснения (Ф2/#899). */
  maxActionsPerRun: 5,
  /** Личная память (#900): активных записей на сотрудника и знаков на запись. */
  maxMemories: 50,
  maxMemoryChars: 300,
  /** Сколько знаков памяти подставляется в системный промпт. */
  maxMemoryPromptChars: 2_000,
} as const;

/** Идентификатор инструмента: `module.action` (внешние — `ext.<server>.<tool>`). */
export const ASSISTANT_TOOL_ID_PATTERN = /^(?:ext\.[a-z0-9_]+|[a-z][a-z0-9_]*)\.([a-z][a-z0-9_]*)$/;
