/**
 * Готовность запроса к выдаче (#952): контракт — `q` не короче 2 символов.
 * Считается по ТЕКУЩЕМУ тексту поля, не по дебаунсу: после очистки строки
 * дебаунс ещё держит прежний запрос, и состояния выдачи («Ничего не
 * найдено», старые строки) мигали поверх подсказки (баг приёмки 18.11.2026).
 */
export function searchQueryReady(query: string): boolean {
  return query.trim().length >= 2;
}
