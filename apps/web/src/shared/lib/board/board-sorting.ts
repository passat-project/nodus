import type { SortingStrategy } from '@dnd-kit/sortable';

/**
 * Нейтральная стратегия сортировки канбан-борда (#737, репро 13.11.2026).
 *
 * Борд переставляется ЖИВОЙ в `onDragMove`: массив карточек уже стоит в том
 * порядке, куда карточка упадёт, а слот переносимой — её DOM-узел на новом
 * месте (пунктирный placeholder). Штатная `verticalListSortingStrategy` для
 * этого режима не годится: она считает трансформы от ТЕКУЩИХ индексов и
 * ВСЕГДА разворачивает сторону вставки — при состоянии «после B» рисует
 * карточку перед B (B сдвигается вниз на высоту активной, активная — вверх),
 * при «перед B» — наоборот. Проверено вызовом `verticalListSortingStrategy`
 * из @dnd-kit/sortable 10.0.0: activeIndex=1/overIndex=0 и
 * activeIndex=0/overIndex=1 дают одинаковые трансформы (item0 +высота,
 * item1 −высота). Пользователь видит фантом на противоположной стороне:
 * «между двумя» и «в самый верх» визуально недостижимы, drop расходится с
 * показанным слотом.
 *
 * Живой перестановке трансформы не нужны вовсе: соседи разъезжаются сменой
 * DOM-порядка. Поэтому стратегия возвращает null для всех элементов —
 * `SortableContext` остаётся (его контекст нужен `useSortable` и
 * клавиатурным координатам), но визуально ничего не двигает.
 */
export const liveBoardSortingStrategy: SortingStrategy = () => null;
