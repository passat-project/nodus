/**
 * Геометрия канбан-доски (#730): одна точка правды для ширины плитки
 * (колонка стадии и «Добавить стадию»), промежутка между плитками и внешних
 * отступов ряда. Читают все доски и скелетон (`BoardScroller`, `BoardColumn`,
 * `KanbanSkeleton`, `TaskStageCreate`) — геометрия чинится в одном месте,
 * доски не расходятся.
 *
 * Требование владельца (уточнение 10.11.2026): не менее 6 плиток на Full HD
 * (1920×1080) при развёрнутом левом меню, «Добавить стадию» — тоже плитка, и
 * **пустого места справа быть не должно**. Отсюда ширина не фиксированная:
 * плитка тянется (flex-1 basis-0) и делит ряд поровну — при 3 плитках они
 * шире, при 6 занимают ряд целиком. Минимум — 1/6 бюджета ряда: ниже него
 * плитка не сжимается, и с 7-й плиткой включается горизонтальный edge-scroll
 * (#366), а каждая держит ту же долю.
 *
 * Бюджет ширины при дефолтном масштабе интерфейса (`--ui-scale: 1.25`,
 * корень 20px): рейка 300 + зазор 10 = 310, правая полоса 50 + зазор 10 = 60,
 * остаётся 1550px; минус внешние отступы ряда (2×16) = 1518px. Шесть плиток
 * при этом — (1518 − 5×10) / 6 ≈ 244.7px на плитку, прокрутки нет.
 *
 * Значения — в rem: масштаб интерфейса двигает плитку и зазоры вместе (при
 * `--ui-scale: 1.25` они дают 10 / 16 экранных px). Типографика по канону —
 * фиксированный px и от масштаба не зависит.
 */

/** Сколько плиток держит ряд по ширине: 6 — включая «Добавить стадию». */
export const BOARD_COLUMNS_PER_VIEW = 6;

/** Плитка тянется: делит ряд поровну, фиксированной ширины нет (иначе справа пусто). */
export const BOARD_COLUMN_GROW_CLASS = 'flex-1 basis-0';

/**
 * Минимальная ширина плитки — 1/6 бюджета ряда: из 100% вычитаются 5
 * промежутков (5 × 0.5rem = 2.5rem) и внешние отступы ряда (2 × 0.8rem =
 * 1.6rem), остаток делится на 6 → 4.1rem/6. Литерал обязателен: Tailwind
 * собирает классы только из статического текста, поэтому формула не собирается
 * из констант — её проверяет unit-тест `board-metrics.test.tsx`.
 */
export const BOARD_COLUMN_MIN_CLASS = 'min-w-[calc((100%_-_4.1rem)_/_6)]';

/** Класс плитки: тянется по ряду, ниже 1/6 бюджета не сжимается. */
export const BOARD_COLUMN_CLASS = `${BOARD_COLUMN_GROW_CLASS} ${BOARD_COLUMN_MIN_CLASS}`;

/** Промежуток между плитками: 0.5rem = 10 экранных px (было 1.25rem/gap-5 = 25). */
export const BOARD_GAP_CLASS = 'gap-2';
/** Внешние отступы ряда: 0.8rem = 16 экранных px с каждой стороны (было 1.5rem/px-6 = 30). */
export const BOARD_EDGE_CLASS = 'px-[0.8rem]';
/** Ряд плиток целиком — общий для доски и её скелетона (иначе геометрия разъезжается).
 *  `overflow-x-auto` — edge-scroll для 7+ плиток; вертикальные отступы — дефолт
 *  проектной доски, «Мой план» переопределяет `pt-1`. */
export const BOARD_ROW_CLASS = `flex h-full ${BOARD_GAP_CLASS} overflow-x-auto ${BOARD_EDGE_CLASS} pt-3 pb-4`;

/** Дефолтный корневой кегль интерфейса, px (`--ui-scale: 1.25` от базы 16). */
const ROOT_PX = 20;
const SPACING_UNIT_REM = 0.25;

function remToPx(className: string): number {
  const rem = Number(className.match(/\[([\d.]+)rem\]/)?.[1]);
  return Math.round(rem * ROOT_PX);
}

function spacingToPx(className: string): number {
  const units = Number(className.match(/(?:gap|p|px)-([\d.]+)/)?.[1]);
  return Math.round(units * SPACING_UNIT_REM * ROOT_PX);
}

/** Промежуток в экранных px при дефолтном масштабе. */
export const BOARD_GAP_PX = spacingToPx(BOARD_GAP_CLASS);
/** Внешний отступ ряда в экранных px при дефолтном масштабе. */
export const BOARD_EDGE_PX = remToPx(BOARD_EDGE_CLASS);
