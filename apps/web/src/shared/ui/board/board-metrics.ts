/**
 * Геометрия канбан-доски (#730, исправление #824): одна точка правды для
 * ширины плитки (колонка стадии и «Добавить стадию»), промежутка между
 * плитками и внешних отступов ряда. Читают все доски и скелетон
 * (`BoardScroller`, `BoardColumn`, `KanbanSkeleton`, `TaskStageCreate`) —
 * геометрия чинится в одном месте, доски не расходятся.
 *
 * Ширина плитки ДИНАМИЧЕСКАЯ, как в Битриксе (замер владельца 12.11.2026 по
 * двум скриншотам доски из 8 стадий): колонка тянется вместе с окном —
 * 259px в узком окне 2248 и 369px в развёрнутом на 3439 (шаг 268/378, зазор
 * ~9). Когда места не хватает до минимума — колонки не сжимаются, а уходят
 * в горизонтальный скролл. Отсюда ПОЛОСА (minmax-паттерн, MDN
 * «repeat(auto-fill, minmax())»): плитка делит ряд поровну, но не уже 12rem
 * (240) и не шире 18rem (360 экранных px при `--ui-scale: 1.25`, корень 20px).
 * Пока честная доля внутри полосы — ряд заполнен без пустого места; выше
 * потолка — плитки держат 360 (шире битриксового max не раздуваем); ниже пола
 * — ряд переполняется и включается edge-scroll (#366), а не сжатие.
 *
 * Арифметика на опорных экранах (бюджет ряда: рейка 15rem + зазор 0.5rem +
 * правая полоса 2.5rem + зазор 0.5rem = 18.5rem; минус внешние отступы
 * 2 × 0.8rem; минус промежутки 0.5rem — те же числа, что в классах):
 * - Full HD 1920×1080 → ряд 77.5rem, контент 75.9rem: 6 плиток — доля
 *   12.23rem (244px) внутри полосы → ровно 6 заполняют ряд (у Битрикса при
 *   окне 2248 — 259, у нас рейка шире на ~10px, поэтому низ 240);
 *   7-я — доля 10.4rem ниже пола → прокрутка.
 * - 2560×1440 → контент 107.9rem: 6 плиток — доля 17.6rem (351px) внутри
 *   полосы → тянутся и заполняют ряд; 8 плиток — 13.05rem (261px) заполняют;
 *   9 — 11.5rem ниже пола → прокрутка. Влезает ровно 8 столбцов.
 * - 3440×1440 → контент 151.9rem: 6 плиток — доля 25.1rem выше потолка →
 *   по 360px (потолок, как битриксовый max 369); 8 — 18.1rem выше потолка →
 *   по 360px (ряд почти полон); 12 — 12.2rem заполняют; 13 — ниже пола.
 *
 * Почему не бесконечная резина (баг приёмки #824: `flex-1 basis-0` без
 * потолка): на ultrawide 3440 шесть колонок раздувались до ~500px —
 * «ужасно широкие». Потолок 360 = битриксовый max (369), пол 240 = «6 плиток
 * на Full HD» и читаемая карточка без сжатия.
 *
 * Значения — в rem: масштаб интерфейса двигает плитку и зазоры вместе (при
 * `--ui-scale: 1.25` они дают 10 / 16 экранных px). Типографика по канону —
 * фиксированный px и от масштаба не зависит.
 */

/** Сколько плиток держит ряд на опорном Full HD: 6 — включая «Добавить стадию». */
export const BOARD_COLUMNS_PER_VIEW = 6;

/** Плитка тянется: делит ряд поровну (доля ограничена полом и потолком ниже). */
export const BOARD_COLUMN_GROW_CLASS = 'flex-1 basis-0';

/**
 * Пол ширины плитки: 12rem = 240 экранных px. Ниже него плитка не сжимается —
 * ряд переполняется и включается горизонтальная прокрутка (edge-scroll #366).
 * Литерал обязателен: Tailwind собирает классы только из статического текста,
 * формулу проверяет unit-тест `board-metrics.test.tsx`.
 */
export const BOARD_COLUMN_MIN_CLASS = 'min-w-[12rem]';

/**
 * Потолок ширины плитки: 18rem = 360 экранных px — битриксовый max 369
 * (замер владельца 12.11.2026: развёрнутое окно 3439 → колонка 369). Выше
 * потолка колонки не раздуваются на ultrawide; свободное место уходит под
 * следующие столбцы.
 */
export const BOARD_COLUMN_MAX_CLASS = 'max-w-[18rem]';

/** Класс плитки: тянется по ряду в полосе 240–360px. */
export const BOARD_COLUMN_CLASS = `${BOARD_COLUMN_GROW_CLASS} ${BOARD_COLUMN_MIN_CLASS} ${BOARD_COLUMN_MAX_CLASS}`;

/** Промежуток между плитками: 0.5rem = 10 экранных px (было 1.25rem/gap-5 = 25). */
export const BOARD_GAP_CLASS = 'gap-2';
/** Внешние отступы ряда: 0.8rem = 16 экранных px с каждой стороны (было 1.5rem/px-6 = 30). */
export const BOARD_EDGE_CLASS = 'px-[0.8rem]';
/** Ряд плиток целиком — общий для доски и её скелетона (иначе геометрия разъезжается).
 *  `overflow-x-auto` — edge-scroll для 7+ плиток; вертикальные отступы — дефолт
 *  проектной доски, «Мой план» переопределяет `pt-1`. */
export const BOARD_ROW_CLASS = `flex h-full ${BOARD_GAP_CLASS} overflow-x-auto ${BOARD_EDGE_CLASS} pt-3 pb-4`;

/** Дефолтный корневой кегль интерфейса, px (`--ui-scale: 1.25` от базы 16). */
const ROOT_PX = 20;
const SPACING_UNIT_REM = 0.25;

function remToPx(className: string): number {
  const rem = Number(className.match(/\[([\d.]+)rem\]/)?.[1]);
  return Math.round(rem * ROOT_PX);
}

function spacingToPx(className: string): number {
  const units = Number(className.match(/(?:gap|p|px)-([\d.]+)/)?.[1]);
  return Math.round(units * SPACING_UNIT_REM * ROOT_PX);
}

/** Промежуток в экранных px при дефолтном масштабе. */
export const BOARD_GAP_PX = spacingToPx(BOARD_GAP_CLASS);
/** Внешний отступ ряда в экранных px при дефолтном масштабе. */
export const BOARD_EDGE_PX = remToPx(BOARD_EDGE_CLASS);
