/**
 * Геометрия канбан-доски (#730, исправление #824): одна точка правды для
 * ширины плитки (колонка стадии и «Добавить стадию»), промежутка между
 * плитками и внешних отступов ряда. Читают все доски и скелетон
 * (`BoardScroller`, `BoardColumn`, `KanbanSkeleton`, `TaskStageCreate`) —
 * геометрия чинится в одном месте, доски не расходятся.
 *
 * Ширина плитки ФИКСИРОВАННАЯ и выведена из опорного экрана — Full HD
 * 1920×1080 при развёрнутом левом меню и дефолтном масштабе
 * (`--ui-scale: 1.25`, корень 20px). Бюджет ряда: рейка 15rem + зазор
 * 0.5rem + правая полоса 2.5rem + зазор 0.5rem = 18.5rem → 77.5rem; минус
 * внешние отступы ряда (2 × 0.8rem) = 75.9rem; минус 5 промежутков
 * (5 × 0.5rem) = 73.4rem на 6 плиток, то есть 12.23rem. В классе — 12.2rem
 * (244 экранных px): 6 плиток + 5 промежутков + отступы = 1546px ≤ 1550px
 * ряда — ровно 6 плиток, включая «Добавить стадию», без прокрутки.
 *
 * Почему фиксированная, а не растяжение по ряду (было `flex-1 basis-0`, баг
 * приёмки #824): на широкоформатном мониторе ряд делился на 6, и колонки
 * становились «ужасно широкими». Теперь плитка держит ширину обычного
 * монитора: на широком в ряд влезают 7+ плиток, на узком плитки не сжимаются
 * — ряд переполняется и включается горизонтальный edge-scroll (#366).
 *
 * Значения — в rem: масштаб интерфейса двигает плитку и зазоры вместе (при
 * `--ui-scale: 1.25` они дают 10 / 16 экранных px). Типографика по канону —
 * фиксированный px и от масштаба не зависит.
 */

/** Сколько плиток держит ряд на опорном Full HD: 6 — включая «Добавить стадию». */
export const BOARD_COLUMNS_PER_VIEW = 6;

/**
 * Ширина плитки — 12.2rem (244 экранных px при `--ui-scale: 1.25`), 1/6
 * бюджета ряда на опорном Full HD (вывод — в шапке файла). `shrink-0`
 * обязателен: иначе flex сжимает плитки при 7+ вместо горизонтальной
 * прокрутки. Литерал обязателен: Tailwind собирает классы только из
 * статического текста, поэтому формула не собирается из констант — её
 * проверяет unit-тест `board-metrics.test.tsx`.
 */
export const BOARD_COLUMN_WIDTH_CLASS = 'w-[12.2rem] shrink-0';

/** Класс плитки: фиксированная ширина опорного Full HD, без роста по ряду. */
export const BOARD_COLUMN_CLASS = BOARD_COLUMN_WIDTH_CLASS;

/** Промежуток между плитками: 0.5rem = 10 экранных px (было 1.25rem/gap-5 = 25). */
export const BOARD_GAP_CLASS = 'gap-2';
/** Внешние отступы ряда: 0.8rem = 16 экранных px с каждой стороны (было 1.5rem/px-6 = 30). */
export const BOARD_EDGE_CLASS = 'px-[0.8rem]';
/** Ряд плиток целиком — общий для доски и её скелетона (иначе геометрия разъезжается).
 *  `overflow-x-auto` — edge-scroll для 7+ плиток; вертикальные отступы — дефолт
 *  проектной доски, «Мой план» переопределяет `pt-1`. */
export const BOARD_ROW_CLASS = `flex h-full ${BOARD_GAP_CLASS} overflow-x-auto ${BOARD_EDGE_CLASS} pt-3 pb-4`;

/** Дефолтный корневой кегль интерфейса, px (`--ui-scale: 1.25` от базы 16). */
const ROOT_PX = 20;
const SPACING_UNIT_REM = 0.25;

function remToPx(className: string): number {
  const rem = Number(className.match(/\[([\d.]+)rem\]/)?.[1]);
  return Math.round(rem * ROOT_PX);
}

function spacingToPx(className: string): number {
  const units = Number(className.match(/(?:gap|p|px)-([\d.]+)/)?.[1]);
  return Math.round(units * SPACING_UNIT_REM * ROOT_PX);
}

/** Промежуток в экранных px при дефолтном масштабе. */
export const BOARD_GAP_PX = spacingToPx(BOARD_GAP_CLASS);
/** Внешний отступ ряда в экранных px при дефолтном масштабе. */
export const BOARD_EDGE_PX = remToPx(BOARD_EDGE_CLASS);
