/**
 * #132 р.2 / #273: исполнитель closeFirst-пунктов контекстных меню. Такие
 * пункты меняют режим селекта («Выбрать»/«Отменить выбор»), и если выполнить
 * действие сразу, контент меню морфится в противоположный набор прямо в
 * анимации закрытия. Поэтому меню закрывается ЯВНО (а не по неявному
 * handleSelect Radix), а действие идёт после анимации закрытия.
 */

/** Длительность анимации закрытия меню (duration-100 + запас на exit). */
export const MENU_CLOSE_ANIMATION_MS = 170;

/** Закрыть меню синхронно и выполнить действие после анимации закрытия. */
export function closeMenuThenRun(close: () => void, run: () => void): void {
  close();
  window.setTimeout(run, MENU_CLOSE_ANIMATION_MS);
}
