--
-- Последствие для существующих данных: ранее «архивные» строки (is_active=false)
-- после этой миграции становятся обычными видимыми должностями — их держатели,
-- включая уволенных, снова видны в справочнике и пикере «Должность». Перед
-- выкаткой на живую базу снять список `SELECT id, name, kind FROM positions
-- WHERE is_active = false` и решить: переназначить держателей и удалить либо
-- оставить (прод — пустая установка, проверка нужна для dev-баз).
--
-- Откат на предыдущий образ (down-миграций в репозитории нет):
--   ALTER TABLE "positions" ADD COLUMN "is_active" boolean NOT NULL DEFAULT true;
--
-- IF EXISTS — повторный прогон на частично применённом окружении не падает
-- (прецедент: 20261125120000_project_group_drop_archive).
