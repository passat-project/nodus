/**
 * Золотой набор запросов для eval каталога ассистента (#926, этап 1).
 *
 * Набор — данные, а не код: формулировки сотрудников четырёх ролей с
 * ожидаемыми и запрещёнными инструментами, обоснованием и признаками
 * «инструмента нет» / «нужно уточнение». Метрики и пороги —
 * `eval-metrics.ts`, прогон — `eval-runner.ts`, CI-гейт — `eval-gate.test.ts`.
 *
 * Данные только обезличенные: вымышленные имена, проекты и номера. Репозиторий
 * публичный, реальные ФИО, адреса и содержимое переписки сюда не попадают.
 */

/** Роли, под которые собраны формулировки (эпик #926). */
export const GOLDEN_ROLES = ['gip', 'secretary', 'admin', 'employee'] as const;
export type GoldenRole = (typeof GOLDEN_ROLES)[number];

/**
 * Форма формулировки: официальная, разговорная, с сокращением/опечаткой.
 * На каждый интент — 2–3 формы: каталог обязан переживать живую речь, а не
 * только аккуратные запросы.
 */
export const GOLDEN_FORMS = ['official', 'colloquial', 'typo'] as const;
export type GoldenForm = (typeof GOLDEN_FORMS)[number];

export interface GoldenCase {
  /** Стабильный id: `<роль>-<тема>-<номер>`, например `employee-tasks-01`. */
  id: string;
  role: GoldenRole;
  form: GoldenForm;
  /** Формулировка сотрудника дословно (обезличенная). */
  query: string;
  /**
   * Инструменты, которые обязаны попасть в top-7: если их нет — это промах
   * выбора. Несколько id — когда для ответа нужен и поиск аргументов, и
   * действие (переходы задачи → сам переход).
   */
  expectedTools: string[];
  /**
   * Инструменты, которых в top-7 быть НЕ должно: правдоподобная, но неверная
   * догадка (например, отправка сообщения на просьбу прочитать).
   */
  forbiddenTools: string[];
  /** Инструмента в каталоге нет: правильный исход — отказ, а не натяжка. */
  noToolCase?: boolean;
  /** Нужно уточнение у сотрудника (неоднозначная ссылка/адресат). */
  shouldClarify?: boolean;
  /** Почему такой ожидаемый набор и такой запрет — одна фраза. */
  rationale: string;
}

/** Границы набора: 100–150 запросов (эпик #926); меньше — не статистика. */
export const GOLDEN_SET_MIN = 100;
export const GOLDEN_SET_MAX = 150;

/** Целевой размер текущего набора. */
export const GOLDEN_SET_SIZE = 120;
