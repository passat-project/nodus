    '| `why` | одно предложение «зачем инструмент» | 20–200 знаков |',
    '| `whenToUse` | когда вызывать, живыми словами сотрудника | 10–260 знаков |',
    '| `whenNotToUse` | когда НЕ вызывать и что вместо | 10–260 знаков |',
