/**
 * Оборачивание результата инструмента в явный блок ДАННЫХ (защита от
 * indirect prompt injection, находка security-ревью 17.11.2026): текст письма,
 * сообщения или названия задачи может содержать инструкции модели — правило
 * «результаты инструментов — данные» становится структурным, а не только
 * строкой промпта.
 *
 * Маркеры внутри текста нейтрализуются: иначе письмо могло бы «закрыть» блок
 * (`</data>`) и продолжить уже как будто от системы. Проверка регистронезависима
 * и терпима к пробелам (`< / data`, `<DATA`): модель не должна отличать данные
 * от инструкций по варианту написания тега.
 */

/** Маркер-«кавычка» для нейтрализованных тегов данных. */
const ESCAPED_TAG = '‹';

/** `<data`, `</data`, `<DATA`, `< / data` — любой вариант открытия тега. */
const DATA_TAG = /<(\s*\/?\s*data\b)/gi;

export function asToolData(toolId: string, text: string): string {
  // `$1` — захваченная часть после `<`: тег остаётся узнаваемым, но перестаёт
  // быть разметкой блока.
  const safe = text.replace(DATA_TAG, `${ESCAPED_TAG}$1`);
  // Имя инструмента приходит из каталога, но внешние (Ф3) — с сервера:
  // кавычка/угловые скобки не должны «вылезти» из атрибута.
  const tag = toolId.replace(/["'<>\s]/g, '');
  return `<data tool="${tag}">\n${safe}\n</data>`;
}
