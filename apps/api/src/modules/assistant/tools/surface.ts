import { ALL_TOOLS } from './catalog.js';
import type { AssistantToolDefinition } from './tool-definition.js';

/**
 * Карта поверхностей ассистента (#918, ADR-0049): инструмент → маршрут API →
 * модуль → право/флаг. Генерируется из каталога — единственного источника
 * правды; CI сравнивает файл с генерацией и падает при расхождении.
 *
 * Зачем: ревьюер и разработчик видят, какие маршруты и DTO «заняты»
 * ассистентом. Меняешь маршрут/поле — обнови инструмент и карту в том же PR.
 */

/** Маркер в шапке: по нему тест отличает сгенерированный файл от ручного. */
export const SURFACE_MAP_MARKER =
  'GENERATED by UPDATE_ASSISTANT_SURFACE=1 pnpm --filter @nodus/api exec vitest run src/modules/assistant/tools/surface.test.ts';

export function renderSurfaceMap(catalog: readonly AssistantToolDefinition[] = ALL_TOOLS): string {
  const rows = [...catalog]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((tool) => {
      const api = tool.api ? `${tool.api.method} ${tool.api.path}` : '—';
      return `| \`${tool.id}\` | ${escapeCell(tool.title)} | ${tool.kind === 'write' ? 'запись' : 'чтение'} | ${tool.module} | ${escapeCell(api)} | ${tool.permission ?? '—'} | ${tool.featureFlag ?? '—'} | ${tool.hot ? 'да' : 'нет'} |`;
    });
  return [
    '# Карта поверхностей ИИ-ассистента',
    '',
    `<!-- ${SURFACE_MAP_MARKER}: не редактируй руками. -->`,
    '',
    'Инструмент = операция API портала (ADR-0043). Таблица строится из каталога',
    '`apps/api/src/modules/assistant/tools/catalog.ts`; проверка свежести —',
    '`surface.test.ts` (CI краснеет при расхождении).',
    '',
    'Обновить: `UPDATE_ASSISTANT_SURFACE=1 pnpm --filter @nodus/api exec vitest run src/modules/assistant/tools/surface.test.ts`',
    '',
    `Всего инструментов: **${catalog.length}** (запись: ${catalog.filter((tool) => tool.kind === 'write').length}).`,
    '',
    '| Инструмент | Название | Вид | Модуль | API | Право | Флаг | Горячая |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, '\\|');
}
