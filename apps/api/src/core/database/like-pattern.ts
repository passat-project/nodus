/**
 * Экранирование пользовательского текста в LIKE-шаблоне (F1, #952).
 *
 * `contains: { mode: 'insensitive' }` Prisma разворачивает в
 * `LIKE '%' || $1 || '%'` и НЕ экранирует метасимволы: запрос «%» находил все
 * строки, «_» — любую букву (соседний баг поиска писем/сотрудников/задач,
 * найден при разработке #952). PostgreSQL по умолчанию считает обратный
 * слэш escape-символом LIKE, поэтому достаточно `\%`/`\_`/`\\`.
 *
 * Один хелпер на все модули: локальные копии расходились (проекты, crm, чат),
 * а новая копия в поиске — это тот же баг четвёртый раз.
 */
export function escapeLikePattern(value: string): string {
  return value.replace(/[\\%_]/gu, (ch) => `\\${ch}`);
}
